# ---------------------------------------------------------------------- 样式
def _run_font(run, size: float, cn: str, bold: bool = False,
              italic: bool = False) -> None:
    """中文用 ``cn``、西文与数字用 Times New Roman（竞赛格式要求）。"""
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.italic = italic
    run.font.name = TNR
    rpr = run._element.get_or_add_rPr()
    rfonts = rpr.find(qn("w:rFonts"))
    if rfonts is None:
        rfonts = OxmlElement("w:rFonts")
        rpr.append(rfonts)
    rfonts.set(qn("w:ascii"), TNR)
    rfonts.set(qn("w:hAnsi"), TNR)
    rfonts.set(qn("w:eastAsia"), cn)


_BOLD_RE = re.compile(r"\*\*(.+?)\*\*", re.S)


def _add_rich(p, text: str, size: float, cn: str, base_bold: bool = False) -> None:
    """写入文本并解析 ``**加粗**`` 标记（论文重点段落需要加粗强调）。"""
    pos = 0
    for m in _BOLD_RE.finditer(text):
        if m.start() > pos:
            _run_font(p.add_run(text[pos:m.start()]), size, cn, base_bold)
        _run_font(p.add_run(m.group(1)), size, cn, True)
        pos = m.end()
    if pos < len(text):
        _run_font(p.add_run(text[pos:]), size, cn, base_bold)


def _para(doc, text: str = "", *, size: float = 12.0, cn: str = SONG,
          bold: bool = False, align=WD_ALIGN_PARAGRAPH.JUSTIFY,
          indent_chars: float = 2.0, line: float = 1.5,
          space_before: float = 0.0, space_after: float = 0.0,
          keep_with_next: bool = False):
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.alignment = align
    pf.line_spacing = line
    pf.space_before = Pt(space_before)
    pf.space_after = Pt(space_after)
    pf.keep_with_next = keep_with_next
    if indent_chars:
        # 以「字符」为单位首行缩进（Word 中显示为「首行缩进 2 字符」）
        pf.first_line_indent = Pt(size * indent_chars)
    if text:
        _add_rich(p, text, size, cn, bold)
    return p


def body(doc, text: str, **kw):
    """正文段落：宋体小四、1.5 倍行距、首行缩进 2 字符。"""
    return _para(doc, text, size=12.0, cn=SONG, **kw)


def h1(doc, text: str):
    """一级标题：黑体四号、左对齐、独立成行、不缩进。"""
    return _para(doc, text, size=14.0, cn=HEI, bold=False,
                 align=WD_ALIGN_PARAGRAPH.LEFT, indent_chars=0,
                 space_before=5.0, space_after=2.0, keep_with_next=True)


def h2(doc, text: str):
    """二级标题：黑体小四、左对齐、不缩进。"""
    return _para(doc, text, size=12.0, cn=HEI, bold=False,
                 align=WD_ALIGN_PARAGRAPH.LEFT, indent_chars=0,
                 space_before=3.0, space_after=1.0, keep_with_next=True)


def h3(doc, text: str):
    """三级标题：黑体小四、左对齐（与二级同字号，靠编号区分层级）。"""
    return _para(doc, text, size=12.0, cn=HEI, bold=False,
                 align=WD_ALIGN_PARAGRAPH.LEFT, indent_chars=0,
                 space_before=2.0, space_after=1.0, keep_with_next=True)


# ---------------------------------------------------------------------- 版面
def add_page_number_footer(doc) -> None:
    """页脚居中插入阿拉伯数字页码（从 1 开始连续编号，符合竞赛规范）。"""
    section = doc.sections[0]
    footer = section.footer
    footer.is_linked_to_previous = False
    p = footer.paragraphs[0] if footer.paragraphs else footer.add_paragraph()
    for r in list(p.runs):
        r._element.getparent().remove(r._element)
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.line_spacing = 1.0
    p.paragraph_format.first_line_indent = Pt(0)
    run = p.add_run()
    _run_font(run, 10.5, SONG)
    begin = OxmlElement("w:fldChar")
    begin.set(qn("w:fldCharType"), "begin")
    instr = OxmlElement("w:instrText")
    instr.set(qn("xml:space"), "preserve")
    instr.text = "PAGE"
    end = OxmlElement("w:fldChar")
    end.set(qn("w:fldCharType"), "end")
    for el in (begin, instr, end):
        run._element.append(el)


def page_break(doc) -> None:
    """插入分页符（摘要页 / 正文 / 附录之间）。"""
    p = doc.add_paragraph()
    p.paragraph_format.first_line_indent = Pt(0)
    p.add_run().add_break(WD_BREAK.PAGE)


def add_table(doc, header, rows, widths=None, size=10.5):
    """生成网格表（宋体五号、居中），表头加粗，单元格支持 ``**加粗**`` 标记。

    为控制版面（正文含参考文献须 ≤ 30 页），单元格内边距与段前后距压到最小。
    """
    table = doc.add_table(rows=1, cols=len(header))
    table.style = "Table Grid"
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    _tight_cell_margins(table)
    for i, text in enumerate(header):
        cell = table.rows[0].cells[i]
        cell.text = ""
        p = cell.paragraphs[0]
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p.paragraph_format.line_spacing = 1.0
        p.paragraph_format.space_before = Pt(0)
        p.paragraph_format.space_after = Pt(0)
        p.paragraph_format.first_line_indent = Pt(0)
        _add_rich(p, str(text), size, SONG, base_bold=True)
    for row in rows:
        cells = table.add_row().cells
        for i, value in enumerate(row):
            cells[i].text = ""
            p = cells[i].paragraphs[0]
            p.alignment = WD_ALIGN_PARAGRAPH.CENTER
            p.paragraph_format.line_spacing = 1.0
            p.paragraph_format.space_before = Pt(0)
            p.paragraph_format.space_after = Pt(0)
            p.paragraph_format.first_line_indent = Pt(0)
            _add_rich(p, "" if value is None else str(value), size, SONG)
    if widths:
        for row in table.rows:
            for i, w in enumerate(widths):
                row.cells[i].width = Cm(w)
    return table


def _tight_cell_margins(table, top=6, bottom=6, left=60, right=60) -> None:
    """把表格单元格内边距压到最小（单位：1/20 磅），减少表格所占高度。"""
    tbl_pr = table._tbl.tblPr
    mar = OxmlElement("w:tblCellMar")
    for tag, value in (("top", top), ("left", left), ("bottom", bottom), ("right", right)):
        node = OxmlElement("w:" + tag)
        node.set(qn("w:w"), str(value))
        node.set(qn("w:type"), "dxa")
        mar.append(node)
    tbl_pr.append(mar)


def add_figure(doc, path: str, width_cm: float = 15.0) -> bool:
    """居中插入图片；文件缺失时返回 False（不中断生成）。"""
    if not os.path.exists(path):
        return False
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.first_line_indent = Pt(0)
    p.paragraph_format.space_before = Pt(6)
    p.paragraph_format.space_after = Pt(0)
    p.add_run().add_picture(path, width=Cm(width_cm))
    return True


def code_block(doc, text: str, size: float = 7.5) -> None:
    """附录源代码：等宽、单倍行距、无缩进，尽量控制页数。"""
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.alignment = WD_ALIGN_PARAGRAPH.LEFT
    pf.line_spacing = 1.0
    pf.space_before = Pt(0)
    pf.space_after = Pt(0)
    pf.first_line_indent = Pt(0)
    run = p.add_run(text)
    run.font.size = Pt(size)
    run.font.name = "Consolas"
    rpr = run._element.get_or_add_rPr()
    rfonts = OxmlElement("w:rFonts")
    rfonts.set(qn("w:ascii"), "Consolas")
    rfonts.set(qn("w:hAnsi"), "Consolas")
    rfonts.set(qn("w:eastAsia"), SONG)
    rpr.append(rfonts)


def load_json(name: str):
    path = os.path.join(ROOT, "results", name)
    if not os.path.exists(path):
        return None
    with io.open(path, "r", encoding="utf-8") as fh:
        return json.load(fh)


def caption(doc, text: str, above: bool = False):
    """图表标注：宋体五号、居中、无缩进（竞赛格式要求）。"""
    return _para(doc, text, size=10.5, cn=SONG,
                 align=WD_ALIGN_PARAGRAPH.CENTER, indent_chars=0,
                 space_before=1.0, space_after=1.5, keep_with_next=above)


