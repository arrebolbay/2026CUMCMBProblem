"""生成 CUMCM 2026 B 题参赛论文（Word 版，用户自行转 PDF）。

⚠ 本文件属于**论文生成代码**，按竞赛要求**不进入论文附录、也不进入支撑材料**。

格式规范实现要点
----------------
* 文档标题：黑体小三、居中；一级标题：黑体四号、左对齐、独立成行；
  二级标题：黑体小四、左对齐；正文宋体小四、字母数字 Times New Roman、
  行距 1.5、首行缩进 2 字符；注释与图表标注宋体五号。
* 标题层级严格用「一、/（一）/1.」三级，不越级、不混用标点。
* 第一页为摘要专用页（含标题与关键词，不超一页）；页码在页脚居中，
  阿拉伯数字从 1 连续编号。
* 参考文献按正文引用次序排列，正文引用处用方括号标注编号。
* 参考文献之前设「AI 工具使用声明」。
* 问题三、问题四按题干「表 1」格式预留表格（正式测试后手工填入）。

用法：
    & 'D:\\Anaconda3\\envs\\CUMCM\\python.exe' src\\make_paper.py
产物：
    附件\\论文.docx
"""
