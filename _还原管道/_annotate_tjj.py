def find_def_line(lines, name):
    """定位 def/class 行（自动跳过装饰器），返回 0 基行号；未找到返回 -1。"""
    pattern = re.compile(r"^\s*(?:def|class)\s+" + re.escape(name) + r"\b")
    for index, text in enumerate(lines):
        if pattern.match(text):
            start = index
            while start > 0 and lines[start - 1].lstrip().startswith("@"):
                start -= 1
            return start
    return -1


def main() -> None:
    total = 0
    for name, header in HEADERS.items():
        path = os.path.join(DIR, name)
        lines = io.open(path, encoding="utf-8").read().splitlines()
        if any("# 【学习注释】" in l for l in lines[:40]):
            print("%-20s 已注释，跳过（避免重复插入）" % name)
            continue
        out = []
        inserted_header = False
        for index, text in enumerate(lines):
            if not inserted_header and index > 6 and not text.startswith("#!"):
                pass
            out.append(text)
        # 文件头注释插在 imports 之前（即第一处非注释、非 shebang 行之前）
        insert_at = 0
        for index, text in enumerate(out):
            stripped = text.strip()
            if stripped.startswith("#!") or stripped.startswith("# -*-"):
                insert_at = index + 1
                continue
            if stripped.startswith("#") and not stripped.startswith("# 【"):
                continue
            insert_at = index
            break
        new_lines = out[:insert_at] + header.strip("\n").splitlines() + \
            [""] + out[insert_at:]
        # 关键函数注释
        for func, comment in INSERTS.get(name, []):
            at = find_def_line(new_lines, func)
            if at < 0:
                print("  [警告] %s 中未找到 %s" % (name, func))
                continue
            indent = " " * (len(new_lines[at]) - len(new_lines[at].lstrip()))
            block = [indent + l if l.strip() else l for l in comment.splitlines()]
            new_lines[at:at] = block + [""]
            total += 1
        src = "\n".join(new_lines) + "\n"
        try:
            ast.parse(src)
            verdict = "语法 OK"
        except SyntaxError as exc:
            verdict = "语法错误 line %d: %s" % (exc.lineno, exc.msg)
        io.open(path, "w", encoding="utf-8").write(src)
        print("%-20s %5d 行  %s" % (name, len(new_lines), verdict))
    print("共插入关键函数注释 %d 处" % total)


if __name__ == "__main__":
    main()

